export function groupArticlesByPillars(articles) {
  const out = new Map(PILLARS.map((p) => [p.id, { ...p, items: [] }]));
  out.set('reference', { id: 'reference', name: 'Reference & Archives', icon: '📚', blurb: 'General reference texts, indices, and foundational archives.', items: [] });

  for (const a of articles) {
    const t = norm(a.title);
    let matched = false;
    for (const p of PILLARS) {
      const explicit = (p.pages || []).some((page) => norm(page) === t);
      if (explicit) {
        out.get(p.id).items.push(a);
        matched = true;
      }
    }
    if (!matched) {
      for (const p of PILLARS) {
        if ((p.keywords || []).some((re) => re.test(a.title))) {
          out.get(p.id).items.push(a);
          matched = true;
          break;
        }
      }
    }
    if (!matched) {
      out.get('reference').items.push(a);
    }
  }

  for (const p of out.values()) p.items.sort((x, y) => x.title.localeCompare(y.title));
  return [...out.values()].filter((p) => p.items.length);
}

