// ── lookups ────────────────────────────────────────────────────────────────────────────────────
const norm = (s) => String(s == null ? '' : s).trim().toLowerCase();

export const getCosmology = (id) => COSMOLOGIES.find((c) => c.id === norm(id)) || null;
export const TRADITIONS = [...new Set(COSMOLOGIES.map((c) => c.tradition))].sort();
export const byTradition = (t) => COSMOLOGIES.filter((c) => c.tradition === norm(t));
export const byForm = (f) => COSMOLOGIES.filter((c) => c.form === norm(f));
export const byCount = (n) => COSMOLOGIES.filter((c) => c.count === n);

/** Entries safe to reproduce in public without a community's consent question. */
export const publicSafe = () => COSMOLOGIES.filter((c) => !c.restricted);
export const restricted = () => COSMOLOGIES.filter((c) => c.restricted);

/**
 * ⭐ Counts shared by traditions that are not in contact — divine-sets.mjs's thesis, in a second domain.
 * Returns the count, who uses it, and an explicit refusal to treat the coincidence as transmission.
 */
export function sharedCounts() {
  const byN = new Map();
  for (const c of COSMOLOGIES) {
    if (c.count == null) continue;
    if (!byN.has(c.count)) byN.set(c.count, []);
    byN.get(c.count).push({ id: c.id, tradition: c.tradition });
  }
  const shared = [...byN.entries()]
    .filter(([, list]) => new Set(list.map((x) => x.tradition)).size > 1)
    .map(([n, list]) => ({ count: n, traditions: list }))
    .sort((a, b) => a.count - b.count);
  return {
    shared,
    reading: 'The count recurs; the roster does not. Hesiod and the Mexica share FIVE and share nothing '
      + 'else — no names, no order, no mechanism of ending. A small integer with a decline built into it '
      + 'is a shape people reach for. Treat a shared count as a fact about counting, not as evidence of '
      + 'contact, unless something ELSE travels with it — a loanword, a technique, a name.',
  };
}

/** Shape check. Returns problems; never throws. */
export function validate() {
  const problems = [];
  for (const c of COSMOLOGIES) {
    const id = c.id;
    if (!Object.hasOwn(FORMS, c.form)) problems.push(`${id}: unknown form ${c.form}`);
    if (!TIERS.includes(c.tier)) problems.push(`${id}: unknown tier ${c.tier}`);
    if (!c.source) problems.push(`${id}: no source`);
    if (typeof c.restricted !== 'boolean') problems.push(`${id}: restricted must be explicit`);
    if (c.count != null && !Number.isInteger(c.count)) problems.push(`${id}: count is not an integer`);
    // A restricted entry must say what is withheld, or the flag is decoration.
    if (c.restricted && !/RESTRICTED/i.test(String(c.note))) problems.push(`${id}: restricted but the note does not say what is withheld`);
  }
  return { ok: problems.length === 0, problems };
}

export function handler(req, res) {
  res.statusCode = 200;
  res.setHeader('content-type', 'application/json; charset=utf-8');
  res.end(JSON.stringify({
    ok: true, service: 'cosmologies',
    counts: { cosmologies: COSMOLOGIES.length, traditions: TRADITIONS.length, restricted: restricted().length },
    forms: FORMS,
    note: 'world ages, emergence and descent. A shared count is a fact about counting, not evidence of '
        + 'contact. Restricted registers are flagged and not reproduced.',
  }, null, 2));
}

