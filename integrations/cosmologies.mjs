// cosmologies.mjs — WORLD AGES, EMERGENCE, AND DESCENT: the accounts of how things came to be.
//
// Seventh in the series with pantheon-map.mjs, divine-sets.mjs, correspondences.mjs, time-cycles.mjs,
// divine-attributes.mjs and day-signs.mjs.
//
// THE GAP THIS FILLS. divine-sets.mjs counts gods — sevens, ogdoads, enneads, twelves — and holds
// eighteen sets, **not one of them from the Americas or Polynesia**. Nothing anywhere in the corpus
// held a WORLD-AGE or an EMERGENCE account, which is the form most of the world's cosmology actually
// takes. A pantheon says who the gods are. A cosmology says what happened, in what order, and how many
// times it has already ended.
//
// ⭐ THE OBSERVATION, and it is divine-sets.mjs's thesis holding in a second domain.
//
// That file found that the ancient world does not organise its gods into lists, it organises them into
// COUNTS — the number comes first and the roster is filled in locally. World-ages do the same thing:
//
//   FIVE — Hesiod's ages of man; the Aztec Five Suns
//   FOUR — the Hindu yugas; the Hopi and Navajo worlds
//
// Hesiod and the Mexica are not in contact. The count recurs because a small integer with a decline
// built into it is a shape human beings reach for, not because somebody carried it across an ocean.
// Recording the count separately from the roster is what makes that visible rather than mysterious —
// and it is the honest alternative to the diffusion argument day-signs.mjs already had to dismantle
// once (see ARTIFACTS there: ōcēlōtl means jaguar, and the "4 Tiger" anomaly is a translation error).
//
// ⭐ THE SECOND FORM, which the Greek and Egyptian material does not prepare you for.
//
// A GENEALOGICAL cosmogony does not narrate events — it recites descent, and it does not stop at the
// gods. The Hawaiian Kumulipo runs from the coral polyp through the sea, the land and the birds to the
// chiefs who commissioned it, in one unbroken line. The cosmology IS the genealogy, and its function is
// to seat a living ruling line inside creation. That is why Hawaiian royal descent belongs in a file
// about cosmology rather than in one about kings: for the aliʻi they are the same document.
//
// ⚠️ RESTRICTED MATERIAL — read before extending this file.
//
// Several traditions here are living, and portions of their cosmology are deliberately not public.
// Hopi and Navajo emergence accounts have esoteric registers held by initiates and clans; Yaqui Waehma
// material is ceremonially restricted. Published summaries exist and are cited, but "an ethnographer
// printed it in 1904" is not the same as "the community consented to its circulation." Every entry
// carries `restricted`, and `publicSafe()` filters on it. **Do not add detail from a restricted
// register because a source is out of copyright.** Copyright expiry is not consent.
//
//   import { COSMOLOGIES, FORMS, byCount, sharedCounts, publicSafe } from './cosmologies.mjs'
//   node integrations/cosmologies.mjs counts

