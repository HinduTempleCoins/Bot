// symbol-library-spec.mjs — the SPEC for the Religious & Occult Symbol Library (knowledge/symbols/).
//
// Image models draw sacred symbols wrong (six-armed ankhs, backwards Tanit signs, Viking "Vegvísir").
// Hathor Studio and the Hierophant use these REAL, sourced objects instead. This file is the data:
// one row per symbol — name, tradition(s), period / first attestation, documented meaning, the figures it
// belongs to (ids from the Hierophant registries), the Wikipedia article(s) the harvester fetches as the
// source, and where the picture comes from:
//
//   file  — a pinned Wikimedia Commons file title (checked against Commons' licence metadata at harvest)
//   q     — a Commons search (SVG only) used when no pinned file / article lead-image is usable
//   cp    — a Unicode code point, rendered from Noto (SIL OFL) when `font: true` or as the fallback
//
// status: 'attested' (ancient/historic use documented), 'disputed' (origin, name or meaning contested),
// 'modern' (the sign, its name or its religious reading is modern — said plainly in `note`).
//
// Figures resolve against hierophant-entities.mjs, pantheon-map.mjs or divine-attributes.mjs
// (symbol-library-spec.test.mjs enforces that). Pure data — no network, no keys.

