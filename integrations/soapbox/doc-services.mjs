// doc-services.mjs — FAX AND DOCUMENT CONVERSION, as a service.
//
// This exists because records-requests.mjs can tell you an office is fax-only and then leave you
// holding a PDF and no fax machine. Twenty-two offices in that registry, fourteen of which cannot
// be emailed, and several of those take fax and nothing else. The gap between "compose the request"
// and "the request arrives" is the product.
//
// THE HONEST STATE OF FAX, because it is not what people assume:
//
//   • THERE IS NO FREE FAX API. Twilio Programmable Fax — the one everybody remembers — was
//     discontinued for all accounts on 17 DECEMBER 2021, after fraudulent traffic made it
//     unsupportable. API calls to it fail outright.
//   • The free CONSUMER services (FaxZero, GotFreeFax) are web forms behind CAPTCHAs, not APIs,
//     and they put THEIR ADVERTISEMENT ON YOUR COVER PAGE.
//   • ⚠️ And that last point is disqualifying for the use this repo has. The reason to fax a
//     government office is that the TRANSMISSION REPORT IS TIMESTAMPED THIRD-PARTY PROOF OF
//     DELIVERY in a way email is not. A report generated by an ad service, from the ad service's
//     number, is much weaker evidence than one from a line in the sender's own name — and an
//     advertisement on the cover page of a bar grievance is its own problem.
//   • Paid is cheap enough that the free tier is a false economy: Telnyx is about $0.007/page with
//     no monthly minimum. Ten four-page faxes is roughly TWENTY-EIGHT CENTS.
//
// So: `recommend()` will not return an ad-supported service for an evidentiary send, and says why.
//
// No credentials here, ever. Providers are described; transports are injected.

