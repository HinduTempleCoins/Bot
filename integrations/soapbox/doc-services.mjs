export const conversion = (id) => CONVERSIONS.find((c) => c.id === str(id)) || null;
export const faxProvider = (id) => FAX_PROVIDERS[str(id).toLowerCase()] || null;

/** What will a send cost? Returns null for an unknown provider rather than guessing zero. */
export function estimateFax({ providerId, pages = 1, faxes = 1 } = {}) {
  const p = faxProvider(providerId);
  if (!p) return null;
  const n = Math.max(0, Math.floor(pages)) * Math.max(0, Math.floor(faxes));
  const usage = round2(n * p.perPageUSD);
  return {
    provider: p.id, pages: n,
    usageUSD: usage,
    monthlyMinUSD: p.monthlyMinUSD,
    totalFirstMonthUSD: round2(Math.max(usage, p.monthlyMinUSD)),
    overMinimum: usage >= p.monthlyMinUSD,
    adCoverPage: p.adCoverPage,
  };
}

/**
 * ⭐ Which provider should actually be used?
 * `evidentiary` is the load-bearing flag: when the transmission report has to serve as proof of
 * delivery, an ad-supported free service is excluded and the reason is returned, not just the
 * exclusion.
 */
export function recommend({ pages = 1, faxes = 1, evidentiary = true } = {}) {
  const totalPages = Math.max(1, Math.floor(pages)) * Math.max(1, Math.floor(faxes));
  const excluded = [];
  const eligible = Object.values(FAX_PROVIDERS).filter((p) => {
    if (evidentiary && p.adCoverPage) {
      excluded.push({ id: p.id, reason:
        'ad-supported: places an advertisement on the cover page and the transmission report '
        + 'belongs to the service, not the sender — unusable where the report is the proof' });
      return false;
    }
    if (p.kind !== 'api') {
      excluded.push({ id: p.id, reason: 'no API — web form behind a CAPTCHA' });
      return false;
    }
    if (p.pageLimit && totalPages > p.pageLimit) {
      excluded.push({ id: p.id, reason: `page limit ${p.pageLimit} < ${totalPages}` });
      return false;
    }
    return true;
  });

  const priced = eligible.map((p) => ({ ...estimateFax({ providerId: p.id, pages, faxes }), label: p.label }))
    .sort((a, b) => a.totalFirstMonthUSD - b.totalFirstMonthUSD
      || a.usageUSD - b.usageUSD
      || a.provider.localeCompare(b.provider));

  return {
    totalPages,
    evidentiary,
    best: priced[0] || null,
    ranked: priced,
    excluded,
    deadEnds: Object.values(DEAD_PROVIDERS).map((d) => ({ id: d.id, diedOn: d.diedOn, note: d.note })),
    manualAlternative: {
      what: 'a public fax machine',
      why: 'for a handful of evidentiary sends this beats every API: the sender holds the original '
         + 'transmission report, in their own hand, from a line not associated with an ad service',
      example: 'Dallas County Law Library — 600 Commerce St., Suite B40 — (214) 653-7481 '
             + '(free Westlaw and Lexis in the same room)',
    },
  };
}

/**
 * Send a fax. Transport injected; there is no network default, for the same reason as mail-oauth —
 * nothing may send by omission and no test may reach a real fax line.
 */
export async function sendFax({ providerId, to, document: doc, credentials, transport } = {}) {
  const p = faxProvider(providerId);
  if (!p) return { ok: false, stage: 'provider', reason: `unknown provider: ${str(providerId)}` };
  if (p.kind !== 'api') {
    return { ok: false, stage: 'provider', reason: `${p.label} has no API — ${p.note}` };
  }
  if (typeof transport !== 'function') {
    return { ok: false, stage: 'transport', reason: 'no transport injected — nothing sends by default' };
  }
  const digits = str(to).replace(/[^\d+]/g, '');
  if (digits.replace(/\D/g, '').length < 10) {
    return { ok: false, stage: 'number', reason: `not a usable fax number: ${str(to)}` };
  }
  if (!doc || !str(doc.filename)) {
    return { ok: false, stage: 'document', reason: 'a document with a filename is required' };
  }
  try {
    const res = await transport({ provider: p, to: digits, document: doc, credentials });
    if (res && res.ok === false) {
      return { ok: false, stage: 'send', reason: str(res.reason) || 'transport reported failure',
        retryable: !!res.retryable, to: digits };
    }
    return { ok: true, to: digits, id: (res && res.id) || null, provider: p.id,
      // the whole reason for faxing: keep whatever proves it went
      transmissionReport: (res && res.transmissionReport) || null };
  } catch (e) {
    const msg = String((e && e.message) || e);
    return { ok: false, stage: 'send', reason: msg, to: digits,
      retryable: /busy|no answer|timeout|temporar|closed/i.test(msg) };
  }
}

export function handler(req, res) {
  const send = (code, obj) => {
    res.writeHead(code, { 'content-type': 'application/json; charset=utf-8' });
    res.end(JSON.stringify(obj, null, 2));
  };
  try {
    return send(200, {
      module: 'doc-services',
      fax: {
        free: false,
        why: 'There is no free fax API. Twilio Programmable Fax was discontinued 17 Dec 2021; the '
           + 'free consumer services are CAPTCHA web forms that put an advertisement on the cover '
           + 'page and keep the transmission report.',
        cheapest: 'telnyx', approxPerPageUSD: FAX_PROVIDERS.telnyx.perPageUSD,
        providers: Object.values(FAX_PROVIDERS).map((p) => ({
          id: p.id, label: p.label, kind: p.kind, perPageUSD: p.perPageUSD,
          monthlyMinUSD: p.monthlyMinUSD, adCoverPage: p.adCoverPage, note: p.note })),
      },
      conversions: CONVERSIONS,
      rules: ['no credentials stored', 'no transport default',
              'ad-supported fax is excluded from evidentiary sends'],
    });
  } catch (e) { return send(500, { error: String((e && e.message) || e) }); }
}

